"""Data models for cross-session-mcp."""

from dataclasses import asdict, dataclass, field
from typing import Any

HARNESSES = ("claude", "agy", "opencode", "codex", "cursor", "copilot")


@dataclass
class SessionSummary:
    """Lightweight session summary for listings and indexing.

    Every date is ISO 8601 UTC (see utils.to_utc_iso).
    """

    session_id: str
    harness: str  # see HARNESSES
    workspace_path: str
    title: str
    created_at: str | None = None
    updated_at: str | None = None
    turn_count: int = 0
    last_prompt: str = ""
    status: str = "active"

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class SessionTurn:
    """A single turn of a session."""

    role: str  # 'user', 'assistant', 'system', 'tool'
    content: str
    timestamp: str | None = None
    tool_calls: list[dict[str, Any]] | None = None

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class SessionDetail:
    """Full detail of a session with its turns."""

    summary: SessionSummary
    turns: list[SessionTurn] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "summary": self.summary.to_dict(),
            "turns": [t.to_dict() for t in self.turns],
        }


@dataclass
class HandoffResult:
    """Extended handoff generated by Gemini (or by the local extractor)."""

    session_id: str
    harness: str
    workspace_path: str
    markdown_handoff: str
    model_used: str
    generated_at: str
    from_cache: bool = False
    focus_area: str = ""
    # session updated_at at generation time; lets the cache be invalidated
    source_updated_at: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class MemoryUpdateResult:
    """Result of `update_project_memory`."""

    workspace_path: str
    markdown: str
    version: int
    up_to_date: bool = False
    digests_generated: int = 0
    digests_cached: int = 0
    llm_calls: int = 0
    model_used: str = ""
    exported_to: str | None = None
    warnings: list[str] = field(default_factory=list)

    def summary(self) -> str:
        if self.up_to_date:
            text = f"Memory v{self.version} already up to date: no LLM call."
        else:
            text = (
                f"Memory v{self.version} updated with {self.model_used}: {self.llm_calls} LLM calls "
                f"({self.digests_generated} new digests, {self.digests_cached} served from cache)."
            )
        if self.exported_to:
            text += f" Exported to {self.exported_to}."
        return " ".join([text] + self.warnings)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)
